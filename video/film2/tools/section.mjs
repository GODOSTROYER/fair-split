// Fair Split film v7: render ONE section on its own, with its narration, as a quick draft to watch.
//   node tools/section.mjs s2            out/preview/s2.mp4 (1920x1080, 30 fps, draft quality)
//   node tools/section.mjs s2 --from 6 --to 12    only seconds 6 to 12 of the section (its own clock)
// It stages a one-section copy of the root in the OS temp folder (the project folders are linked, not copied), so
// nothing is added to video/film2 but the draft in out/. Only that section is mounted, at 0.
// The section file is not changed and needs nothing special: FILM.at() is already local to the section.
import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readFileSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const timing = JSON.parse(readFileSync(join(root, "timing.json"), "utf8"));
const args = process.argv.slice(2);
const section = timing.sections.find((entry) => entry.id === args[0]);
if (!section) {
  console.error(
    `usage: node tools/section.mjs <${timing.sections.map((entry) => entry.id).join("|")}> [--from s] [--to s]`,
  );
  process.exit(2);
}
const option = (name, fallback) => (args.includes(name) ? Number(args[args.indexOf(name) + 1]) : fallback);
const from = option("--from", 0);
const to = option("--to", section.duration);
const length = Math.round((to - from) * 1000) / 1000;
const id = `preview-${section.id}`;
const { width, height } = timing.canvas;

// The whole section is always rendered; --from and --to cut the finished draft with ffmpeg.
const html = `<!doctype html>
<!-- Generated by tools/section.mjs: section ${section.id} alone. Do not edit, do not commit. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=${width}, height=${height}" />
    <title>Fair Split film v7: ${section.id} alone</title>
    <link rel="stylesheet" href="film.css" />
    <script src="assets/vendor/gsap.min.js"></script>
    <script src="film-data.js"></script>
    <script src="film.js"></script>
    <script src="assets/objects/objects.js"></script>
  </head>
  <body>
    <div id="root" data-composition-id="${id}" data-start="0" data-width="${width}" data-height="${height}" data-duration="${section.duration}">
      <div id="film-ground"></div>
      <div id="sec-${section.id}" data-composition-id="${section.composition}" data-composition-src="${section.file}" data-start="0" data-duration="${section.duration}" data-track-index="1" data-width="${width}" data-height="${height}"></div>
      <audio id="vo-${section.id}" src="audio/narration/${section.id}.m4a" data-start="0" data-duration="${section.duration}" data-track-index="10" data-volume="1"></audio>
    </div>
    <script>
      window.__timelines["${id}"] = gsap.timeline({ paused: true });
    </script>
  </body>
</html>
`;
// stage: <temp>/fair-split-film2-preview/<id>/ with index.html, the root's scripts and links to the project folders
const stage = join(tmpdir(), "fair-split-film2-preview", section.id);
mkdirSync(stage, { recursive: true });
mkdirSync(join(root, "out", "preview"), { recursive: true });
const run = (command) => spawnSync(command, { cwd: root, shell: true, stdio: "inherit" }).status ?? 1;
run("node tools/sync.mjs");
for (const folder of ["assets", "compositions", "audio", "stills"])
  if (!existsSync(join(stage, folder)) && existsSync(join(root, folder)))
    symlinkSync(join(root, folder), join(stage, folder), "junction");
for (const file of ["film.css", "film.js", "film-data.js"]) copyFileSync(join(root, file), join(stage, file));
writeFileSync(join(stage, "index.html"), html);
writeFileSync(
  join(stage, "hyperframes.json"),
  JSON.stringify({ name: id, entry: "index.html", width, height, fps: 30 }, null, 2),
);

const whole = join(root, "out", "preview", `${section.id}.mp4`);
let status = run(`npx hyperframes render "${stage}" --fps 30 --quality draft --output "${whole}"`);
if (status === 0 && (from > 0 || to < section.duration)) {
  const part = join(root, "out", "preview", `${section.id}-${from}-${to}.mp4`);
  status = run(
    `ffmpeg -v error -y -ss ${from} -i "${whole}" -t ${length} -c:v libx264 -crf 16 -c:a aac "${part}"`,
  );
  if (status === 0) console.log(`wrote ${part}`);
}
process.exit(status);

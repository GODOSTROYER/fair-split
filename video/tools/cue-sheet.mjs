// AUDIO-CUES.md, the film's sound sheet (rough cut v5): every narration line where the recorded voice says it, how
// it fits the picture, the music bed's pieces, every sound-effect cue beside its picture event, and the mix. Written
// by build.mjs from script.ts, plan.mjs, audio/narration/manifest.json, sfx-cues.json and build-music-bed.mjs.
import { readFileSync } from "node:fs";
import { eventTime, MEMBER_CLIP, NARRATION_FIT } from "../plan.mjs";
import { beats, FILM, NARRATION_AT } from "../script.ts";
import { AURORA, pieces } from "./build-music-bed.mjs";
import { TARGET } from "./mix.mjs";

const video = new URL("../", import.meta.url);
const mmss = (t) => {
  const tenths = Math.round(t * 10);
  return `${Math.floor(tenths / 600)}:${String(Math.floor(tenths / 10) % 60).padStart(2, "0")}.${tenths % 10}`;
};
const span = (a, b) => `${mmss(a)}–${mmss(b)}`;
const wordsIn = (say) => say.split(/\s+/).filter((word) => /[\p{L}\p{N}]/u.test(word)).length;

/** Each narration fit, measured on the recorded voice: the time and whether it holds. */
export function fitResults() {
  return NARRATION_FIT.map((fit) => {
    const beat = beats.find((item) => item.id === fit.beat);
    const t =
      fit.word === "^"
        ? beat.speech[0]
        : fit.word === "$"
          ? beat.speech[1]
          : beat.words.find((w) => w.w.toLowerCase().replace(/^\W+/, "").startsWith(fit.word)).start;
    return { ...fit, t, ok: t >= fit.within[0] - 1e-6 && t <= fit.within[1] + 1e-6 };
  });
}

export function cueSheet(captions) {
  const manifest = JSON.parse(readFileSync(new URL("audio/narration/manifest.json", video), "utf8"));
  const cues = JSON.parse(readFileSync(new URL("sfx-cues.json", video), "utf8"));
  const narration = beats
    .filter((beat) => beat.id !== "listening")
    .map((beat) => {
      const [from, to] = beat.speech ?? [beat.start, beat.end];
      const clip = manifest.beats.find((item) => item.beat === beat.id);
      const own = captions.filter((cue) => cue.beat === beat.id);
      return `| ${span(from, to)} | ${beat.id} | ${clip ? `${clip.duration} s (take ${clip.take}, at ${mmss(NARRATION_AT[beat.id])})` : "none"} | ${wordsIn(beat.say)} | ${Math.round((wordsIn(beat.say) / (to - from)) * 60)} | ${own.map((cue) => `${mmss(cue.start)} ${cue.lines.join(" ")}`).join("<br>")} |`;
    });
  const fits = fitResults().map(
    (fit) =>
      `| ${fit.beat} | ${fit.what} | ${mmss(fit.t)} | ${span(...fit.within)} | ${fit.ok ? "holds" : "**misses**"} |`,
  );
  const bed = pieces().map(
    (piece) =>
      `| ${span(...piece.film)} | ${piece.track === "machina" ? "Machina" : "Aurora"} from ${mmss(piece.src)} | ${piece.fade[0]} s / ${piece.fade[1]} s | ${piece.lufs} LUFS | ${piece.why} |`,
  );
  const sfx = cues.cues.map((cue) => {
    const t = eventTime(cue.event) + cue.offset;
    const names = Array.isArray(cue.sound) ? cue.sound : [cue.sound];
    const sound = names.map((name) => cues.sounds[name].title).join(", ");
    return `| ${mmss(t)} | \`${cue.event}\`${cue.offset ? ` ${cue.offset > 0 ? "+" : ""}${cue.offset} s` : ""} | ${names.length > 1 ? `${names.length} notes, ${cue.step} s apart: ` : ""}${sound}${cue.repeat ? " (twice)" : ""} | ${cue.picture} |`;
  });
  const her = MEMBER_CLIP.speech;
  return `# Fair Split film: sound (rough cut v5)

Generated by \`video/build.mjs\` (\`tools/cue-sheet.mjs\`) from \`script.ts\`, \`plan.mjs\`, \`audio/narration/manifest.json\`,
\`sfx-cues.json\` and \`tools/build-music-bed.mjs\`; do not edit by hand. Owner's sound decision (5 Nov, ADR-0018):
narration by Gemini TTS, voice Charon (disclosed: "Synthetic voices · Gemini TTS"); music, Scott Buckley's "Machina"
into "Aurora" (CC BY 4.0, credited); CC0 sound effects from the Barty-Bart sound-effects kit, with Fair Split's own
product sounds for product moments. \`out/rough-cut-v5.mp4\` carries the mix and the soft English caption track
(\`captions.vtt\`). Times are film time (m:ss.t), measured on the recorded voice (aligned offline).

## Narration lines

| Speech | Beat | Clip | Words | wpm | Caption cues (start, words) |
| ------ | ---- | ---- | ----- | --- | --------------------------- |
${narration.join("\n")}

The listening beat carries no narration. Member audio alone: her IC-11 PREMIUM sentence plays from ${mmss(MEMBER_CLIP.start)}
(speech ${span(...her)}), with no narration, no music and no sound effect under it.

## Fit to the picture

| Beat | Rule | Said at | Allowed | Result |
| ---- | ---- | ------- | ------- | ------ |
${fits.join("\n")}

## Music bed

Cuts, fades and one level per piece (\`tools/build-music-bed.mjs\`, \`out/music-bed.wav\`, git-ignored). Where each
piece sits in its track was measured, not heard: Aurora's build arrives at ${AURORA.arrival} s, its climax is at
${AURORA.peak} s and its calm tail starts at ${AURORA.calm} s; Machina is a low drone with no percussion, so there is no
beat grid to cut to. **The swell: dark to bright** is Aurora's build arriving on the turn.

| Film | Track | Fade in / out | Level | Why |
| ---- | ----- | ------------- | ----- | --- |
${bed.join("\n")}

## Sound effects

One real sound per cue, keyed to a timeline event (\`plan.mjs\` \`eventTime\`) so it follows any retiming. ${cues.cues.length} cues in
${FILM.duration} s, about one every ${(FILM.duration / cues.cues.length).toFixed(1)} s; none between ${mmss(MEMBER_CLIP.start)} and ${mmss(MEMBER_CLIP.start + MEMBER_CLIP.seconds)}.

| Time | Event | Sound | Picture |
| ---- | ----- | ----- | ------- |
${sfx.join("\n")}

## Mix

\`tools/mix.mjs\`: the bed ducks under each line (starting ${TARGET.attack} s before it, releasing over ${TARGET.release} s after it, a
pause of ${TARGET.innerGap} s or more inside a line lets it rise) and crossfades there to a copy with the voice's band carved
out, line by line ${TARGET.musicUnder} dB under the voice; the effects sit about 24 dB under the voice while it speaks and 16 dB
under it in a gap; the master is ${TARGET.lufs} LUFS integrated with the true peak at or under ${TARGET.truePeak} dBTP, measured on
the exported MP4. The product's own sound in the captures stays muted (\`FILM.capture\`): the film adds its own cues.
`;
}

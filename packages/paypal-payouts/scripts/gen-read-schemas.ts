// Regenerates src/agent-read-schemas.ts: the JSON Schemas of the agent's two payout read tools,
// converted from the vendored PR #107 zod schemas exactly as the toolkit's /openai export converts its
// own tools (zod-to-json-schema, draft-07, inlined). A dev-time step only: the runtime reads the
// checked-in file, and test/agent-read-schemas.test.ts fails if it drifts from parameters.ts.
//
// Run: corepack pnpm --filter @fairsplit/paypal-payouts gen:read-schemas

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { zodToJsonSchema } from "zod-to-json-schema";
import { getPayoutBatchParameters, getPayoutItemParameters } from "../src/parameters.js";

export function readToolJsonSchemas(): Record<"get_payout_batch" | "get_payout_item", unknown> {
  return {
    get_payout_batch: zodToJsonSchema(getPayoutBatchParameters({})),
    get_payout_item: zodToJsonSchema(getPayoutItemParameters({})),
  };
}

const HEADER = `// GENERATED by scripts/gen-read-schemas.ts: do not edit. The JSON Schemas of the agent's two payout
// read tools, converted from parameters.ts (PR #107's schemas) by zod-to-json-schema, the converter the
// toolkit's /openai export bundles. Checked in so the runtime needs no converter (the architecture pins
// zod-to-json-schema for the S2 fallback only); test/agent-read-schemas.test.ts fails if this drifts.
`;

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "agent-read-schemas.ts");
  const body = JSON.stringify(readToolJsonSchemas(), null, 2);
  writeFileSync(out, `${HEADER}\nexport const AGENT_READ_TOOL_JSON_SCHEMAS = ${body} as const;\n`);
  console.log(`wrote ${out}`);
}

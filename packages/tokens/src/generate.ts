const CSS_HEADER =
  "/* Generated by @fairsplit/tokens from src/tokens.ts. Do not edit; run its build script. */\n";
const TS_HEADER =
  "// Generated by @fairsplit/tokens from src/tokens.ts. Do not edit; run its build script.\n";

/** Relative path from src/generated/ to the committed web fonts. */
const FONT_DIR = "../../../../assets/fonts/web";
const ASSETS = resolve(dirname(fileURLToPath(import.meta.url)), "../../../assets");

const px = (n: number) => (n === 0 ? "0" : `${n}px`);
const rem = (n: number) => `${Math.round((n / 16) * 10_000) / 10_000}rem`;
const camel = (s: string) => s.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());

// ------------------------------------------------------------------------------------------------ CSS

function themeBlock(theme: ThemeName, value: "css" | "cssOklch"): string[] {
  const resolved = RESOLVED[theme];
  const lines = COLOUR_NAMES.map((name) => `  --fs-${name}: ${resolved[name][value]};`);
  if (value === "css") {
    lines.unshift(`  color-scheme: ${THEME_INFO[theme].scheme};`);
    lines.push(`  --fs-shadow-paper: ${SHADOWS[theme].paper};`);
    lines.push("  --fs-flash: var(--fs-pencil-wash);");
  }
  return lines;
}

const SELECTOR: Readonly<Record<ThemeName, string>> = {
  tablea: ':root,\n[data-theme="tablea"]',
  adlaw: '[data-theme="adlaw"]',
};

function typeRoleCss(name: string, role: TypeRole): string {
  const lines = [
    `.fs-t-${name} {`,
    `  font-family: var(--fs-font-${role.family === "hollow" ? "ui" : role.family});`,
    `  font-stretch: ${role.stretch}%;`,
    `  font-weight: ${role.weight};`,
    `  font-size: ${rem(role.size)};`,
    `  line-height: ${rem(role.line)};`,
  ];
  if (role.figures) lines.push("  font-variant-numeric: tabular-nums lining-nums;");
  lines.push("}");
  return lines.join("\n");
}

export function renderThemeCss(): string {
  const out: string[] = [CSS_HEADER];
  for (const theme of THEMES) out.push(`${SELECTOR[theme]} {\n${themeBlock(theme, "css").join("\n")}\n}\n`);
  const oklch = THEMES.map(
    (theme) =>
      `  ${SELECTOR[theme].replace("\n", "\n  ")} {\n${themeBlock(theme, "cssOklch")
        .map((l) => `  ${l}`)
        .join("\n")}\n  }`,
  );
  out.push(`@supports (color: oklch(0 0 0)) {\n${oklch.join("\n\n")}\n}\n`);

  const root: string[] = [];
  for (const [role, stack] of Object.entries(FONT_STACKS)) root.push(`  --fs-font-${role}: ${stack};`);
  for (const s of SPACE) root.push(`  --fs-space-${s}: ${px(s)};`);
  for (const [k, v] of Object.entries(RADII)) root.push(`  --fs-radius-${k}: ${px(v)};`);
  for (const [k, v] of Object.entries(DEPTH)) root.push(`  --fs-depth-${k}: ${px(v)};`);
  for (const [k, v] of Object.entries(LAYERS)) root.push(`  --fs-z-${k}: ${v};`);
  for (const [surface, values] of Object.entries(LAYOUT)) {
    for (const [k, v] of Object.entries(values)) {
      const unit = k === "columns" ? String(v) : k === "measure" ? `${v}ch` : px(v);
      root.push(`  --fs-${surface}-${camelToKebab(k)}: ${unit};`);
    }
  }
  root.push(`  --fs-hatch-line: ${px(MATERIALS.hatch.line)};`);
  root.push(`  --fs-hatch-gap: ${px(MATERIALS.hatch.gap)};`);
  root.push(`  --fs-steel-gap: ${px(MATERIALS.steel.gap)};`);
  root.push(`  --fs-focus-width: ${px(MATERIALS.focus.width)};`);
  root.push(`  --fs-focus-offset: ${px(MATERIALS.focus.offset)};`);
  root.push(`  --fs-stamp-size: ${px(MATERIALS.stamp.size)};`);
  root.push(`  --fs-hollow-stroke: ${px(HOLLOW.stroke)};`);
  root.push(`  --fs-noise-opacity: ${MATERIALS.noise.opacity};`);
  for (const [name, t] of Object.entries(TWEENS)) root.push(`  --fs-dur-${camelToKebab(name)}: ${t.ms}ms;`);
  for (const name of Object.keys(EASE))
    root.push(`  --fs-ease-${name}: ${cssEase(name as keyof typeof EASE)};`);
  for (const [name, s] of Object.entries(SPRINGS)) {
    root.push(`  --fs-spring-${name}: ${multiline(springLinearEasing(name as keyof typeof SPRINGS))};`);
    root.push(`  --fs-spring-${name}-dur: ${Math.round(s.settleMs)}ms;`);
  }
  root.push("  --fs-motion: 1;");
  out.push(`:root {\n${root.join("\n")}\n}\n`);

  out.push(
    [
      "/* Reduced motion: no spatial travel; colour and opacity changes stay, at 150 ms (design §3). */",
      "@media (prefers-reduced-motion: reduce) {",
      "  :root {",
      "    --fs-motion: 0;",
      "  }",
      "}",
      "",
      '[data-motion="reduced"] {',
      "  --fs-motion: 0;",
      "}",
      "",
      "/* Only the /prototype gallery sets this, when a viewer asks to compare against the full renderer. */",
      '[data-motion="full"] {',
      "  --fs-motion: 1;",
      "}",
      "",
    ].join("\n"),
  );

  for (const [name, role] of Object.entries(TYPE_ROLES)) out.push(`${typeRoleCss(name, role)}\n`);
  out.push(
    [
      ".fs-figures {",
      "  font-variant-numeric: tabular-nums lining-nums;",
      "}",
      "",
      "/* Mona's straight-bar zero (ss08), kept for the G1 comparison with the default slashed zero. */",
      ".fs-zero-bar {",
      '  font-feature-settings: "ss08" 1;',
      "}",
      "",
    ].join("\n"),
  );
  return out.join("\n");
}

/** Breaks a long CSS function onto one argument per line, as Biome's CSS formatter does. */
function multiline(fn: string): string {
  const open = fn.indexOf("(");
  const args = fn.slice(open + 1, -1).split(", ");
  const lines = args.map((a) => `    ${a}`).join(",\n");
  return `${fn.slice(0, open)}(\n${lines}\n  )`;
}

function camelToKebab(s: string): string {
  return s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`).replace(/([a-z])(\d)/g, "$1-$2");
}

function fontFace(family: string, file: string, descriptors: string[]): string {
  return [
    "@font-face {",
    `  font-family: "${family}";`,
    `  src: url("${FONT_DIR}/${file}") format("woff2");`,
    ...descriptors.map((d) => `  ${d}`),
    "  font-style: normal;",
    "  font-display: swap;",
    "}",
  ].join("\n");
}

/** Console and stage: the full variable FS Sans, the peso face, hollow numerals, stencil, Atkinson (lazy). */
export function renderFontsCss(): string {
  const ui = ["font-weight: 200 900;", "font-stretch: 75% 125%;"];
  return `${CSS_HEADER}
${[
  fontFace("FS Sans", "FSSans-VF.woff2", ui),
  "/* Mona Sans has no peso sign: Noto's joins the family with identical descriptors (assets/fonts/README.md). */",
  fontFace("FS Sans", "FSSansPeso.woff2", [...ui, "unicode-range: U+20B1;"]),
  fontFace("FS Numerals Hollow", "FSNumeralsHollow.woff2", ["font-weight: 800;", "font-stretch: 75%;"]),
  fontFace("FS Stencil", "FSStencil.woff2", ["font-weight: 800;"]),
  "/* Downloaded only when statement prose renders. */",
  fontFace("Atkinson Hyperlegible Next", "AtkinsonNext-VF.woff2", ["font-weight: 400 700;"]),
].join("\n\n")}\n`;
}


// Byte helpers that run unchanged in a browser, in Node and in React Native (Hermes has no `Buffer`, no
// `crypto.subtle` and, depending on the version, no `btoa`): UTF-8, hex, base64, a synchronous SHA-256
// (FIPS 180-4), RFC 9530 `Content-Digest` and UUIDv7. Property-tested against node:crypto.

const encoder = new TextEncoder();

export function utf8(text: string): Uint8Array {
  return encoder.encode(text);
}

export function toHex(bytes: Uint8Array): string {
  let out = "";
  for (const b of bytes) out += b.toString(16).padStart(2, "0");
  return out;
}

export function fromHex(hex: string): Uint8Array {
  if (hex.length % 2 !== 0 || !/^[0-9a-fA-F]*$/.test(hex)) throw new TypeError("not a hex string");
  const out = new Uint8Array(hex.length / 2);
  for (let i = 0; i < out.length; i++) out[i] = Number.parseInt(hex.slice(i * 2, i * 2 + 2), 16);
  return out;
}

const B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
const b64 = (n: number) => B64.charAt(n & 63);

/** Standard base64 with padding (what RFC 9530 byte sequences use). */
export function toBase64(bytes: Uint8Array): string {
  let out = "";
  let i = 0;
  for (; i + 2 < bytes.length; i += 3) {
    const n = ((bytes[i] as number) << 16) | ((bytes[i + 1] as number) << 8) | (bytes[i + 2] as number);
    out += b64(n >> 18) + b64(n >> 12) + b64(n >> 6) + b64(n);
  }
  const rest = bytes.length - i;
  if (rest === 1) {
    const n = (bytes[i] as number) << 16;
    out += `${b64(n >> 18)}${b64(n >> 12)}==`;
  } else if (rest === 2) {
    const n = ((bytes[i] as number) << 16) | ((bytes[i + 1] as number) << 8);
    out += `${b64(n >> 18)}${b64(n >> 12)}${b64(n >> 6)}=`;
  }
  return out;
}

